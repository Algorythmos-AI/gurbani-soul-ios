"""Natural Earth land (world-atlas TopoJSON) -> a clipped, simplified Swift polygon table for the
South-Asia region the Voices map covers. Usage: curl -O https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-50m.json && python3 -I ios/tools/voices_coastline.py land-50m.json ios/App/Sources/Data/SouthAsiaLand.swift"""
import json, sys

LON0, LON1, LAT0, LAT1 = 60.0, 98.0, 5.0, 38.0
EPS = 0.06   # degrees, Douglas-Peucker tolerance


def decode(topo):
    sx, sy = topo['transform']['scale']; tx, ty = topo['transform']['translate']
    arcs = []
    for arc in topo['arcs']:
        x = y = 0; pts = []
        for dx, dy in arc:
            x += dx; y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)
    def ring(idx):
        out = []
        for i in idx:
            a = arcs[i] if i >= 0 else list(reversed(arcs[~i]))
            out.extend(a if not out else a[1:])
        return out
    polys = []
    for g in topo['objects']['land']['geometries']:
        gs = g['arcs'] if g['type'] == 'MultiPolygon' else [g['arcs']]
        for p in gs:
            polys.append(ring(p[0]))     # outer ring only (lakes are irrelevant at this scale)
    return polys


def clip(poly):
    """Sutherland-Hodgman against the bbox."""
    def inside(p, e):
        return [p[0] >= LON0, p[0] <= LON1, p[1] >= LAT0, p[1] <= LAT1][e]
    def inter(a, b, e):
        if e < 2:
            x = LON0 if e == 0 else LON1
            t = (x - a[0]) / (b[0] - a[0]); return (x, a[1] + t * (b[1] - a[1]))
        y = LAT0 if e == 2 else LAT1
        t = (y - a[1]) / (b[1] - a[1]); return (a[0] + t * (b[0] - a[0]), y)
    out = poly
    for e in range(4):
        if not out: break
        inp, out = out, []
        for i, cur in enumerate(inp):
            prev = inp[i - 1]
            if inside(cur, e):
                if not inside(prev, e): out.append(inter(prev, cur, e))
                out.append(cur)
            elif inside(prev, e):
                out.append(inter(prev, cur, e))
    return out


def dp(pts, eps):
    if len(pts) < 3: return pts
    a, b = pts[0], pts[-1]
    dx, dy = b[0] - a[0], b[1] - a[1]
    n = (dx * dx + dy * dy) ** 0.5 or 1e-12
    dmax, idx = 0, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + b[0] * a[1] - b[1] * a[0]) / n
        if d > dmax: dmax, idx = d, i
    if dmax > eps:
        return dp(pts[:idx + 1], eps)[:-1] + dp(pts[idx:], eps)
    return [a, b]


def main():
    topo = json.load(open(sys.argv[1]))
    shapes = []
    for poly in decode(topo):
        c = clip(poly)
        if len(c) < 3: continue
        # a closed ring degenerates under Douglas-Peucker: split at the vertex farthest from the
        # first and simplify each half
        far = max(range(len(c)), key=lambda i: (c[i][0] - c[0][0]) ** 2 + (c[i][1] - c[0][1]) ** 2)
        s = dp(c[:far + 1], EPS)[:-1] + dp(c[far:] + [c[0]], EPS)[:-1]
        area = abs(sum(s[i][0] * s[i - 1][1] - s[i - 1][0] * s[i][1] for i in range(len(s)))) / 2
        if len(s) >= 3 and area > 0.15: shapes.append(s)
    shapes.sort(key=len, reverse=True)
    lines = ['// Generated by ios/tools/voices_coastline.py from Natural Earth 1:50m land (public domain),',
             '// via world-atlas 2.0.2 (ISC, © Mike Bostock). Clipped to lon 60–98°E, lat 5–38°N and',
             '// simplified (Douglas-Peucker 0.06°). Coastline only — no modern borders, which did not',
             '// exist in the centuries the voices lived. Do not edit by hand.',
             'import CoreGraphics', '',
             'enum SouthAsiaLand {',
             f'    static let lonRange: ClosedRange<Double> = {LON0}...{LON1}',
             f'    static let latRange: ClosedRange<Double> = {LAT0}...{LAT1}',
             '    /// Polygons as (lon, lat) pairs.',
             '    static let polygons: [[(Double, Double)]] = [']
    total = 0
    for s in shapes:
        total += len(s)
        body = ', '.join(f'({x:.2f}, {y:.2f})' for x, y in s)
        lines.append(f'        [{body}],')
    lines += ['    ]', '}', '']
    open(sys.argv[2], 'w').write('\n'.join(lines))
    print(f'{len(shapes)} polygons, {total} points')


main()
